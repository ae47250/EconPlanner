			<div class="intro"><p>Cultural Anthropology at Hanover College offers students a deep and comparative understanding of human cultures across time and place. Through global and topical courses, students explore how people create meaning through social institutions such as kinship, religion, politics, language, and art. The program emphasizes ethnographic inquiry, cross-cultural analysis, and critical engagement with issues such as globalization, development, migration, gender, and spirituality. Students build strong research and communication skills through methods courses, collaborative projects, writing-intensive seminars, and optional internships or fieldwork. With opportunities to study regions including Africa, Asia, the Middle East, and the Americas, Cultural Anthropology prepares students for graduate study or careers in education, international development, social services, public policy, or cultural heritage work.</p></div>


