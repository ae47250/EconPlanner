		<header class="section_header"><span class="title">Degree Program : Data Science</span></header>
		
		<div class="section_content">
			
			<div class="intro"><p>In studying Data Science, students learn how to work with quantitative and qualitative data,
		ask interesting questions, evaluate claims, draw inferences, and effectively communicate datadriven answers to real-world problems. Data scientists are professionals who turn data into
		information, so mathematical and statistical knowledge is important. But Data Science is not
		just math and statistics; data scientists also need skills in the following areas:</p>
		<ul>
			<li>Writing computer code to analyze large data sets. Good programmers have self-reliance, but
			also know when to ask for help. They enjoy working in a logical and detail-oriented way and
			are persistent in the face of difficulties.</li>
			<li>Being curious and creative problem solvers. Curiosity is characterized by a desire to ask
			questions, seek the answers, and acquire an underlying knowledge of why things happen in a
			particular way.</li>
			<li>Being effective collaborators. Data scientists have to be able to work independently at times,
			but there are also many situations where they need to collaborate with colleagues.</li>
			<li>Facing down challenges. When things go awry, the data scientist needs to assess how to make
			a "course correction" to get the project back on track for successful completion.</li>
			<li>Communicating results in writing, in visuals, and in spoken form. After working diligently to
			arrive at interesting conclusions, it's important to communicate those conclusions clearly and
			effectively.</li>
		</ul>
		<p>Interested students are advised to begin their program of study in their first year by taking
		Calculus I (MAT 121) and Introduction to Data Science (DSCI 110). They should also make
		an expeditious start on the computer science requirements.</p>
		<p>Students are advised to consult with a member of the Data Science faculty to plan a four-year
		course of study as early as possible, as several of the required courses are only offered every
		second year.</p>
